package send

const (
	VK_MENU    = 0x12
	VK_NUMPAD1 = 0x61
	VK_NUMPAD2 = 0x62
)

var usScan = map[rune]uint16{
	'1': 0x02, '2': 0x03, '3': 0x04, '4': 0x05, '5': 0x06,
	'6': 0x07, '7': 0x08, '8': 0x09, '9': 0x0A, '0': 0x0B,
	'q': 0x10, 'w': 0x11, 'e': 0x12, 'r': 0x13, 't': 0x14,
	'y': 0x15, 'u': 0x16, 'i': 0x17, 'o': 0x18, 'p': 0x19,
	'a': 0x1E, 's': 0x1F, 'd': 0x20, 'f': 0x21, 'g': 0x22,
	'h': 0x23, 'j': 0x24, 'k': 0x25, 'l': 0x26,
	'z': 0x2C, 'x': 0x2D, 'c': 0x2E, 'v': 0x2F, 'b': 0x30,
	'n': 0x31, 'm': 0x32,
	'-': 0x0C, '=': 0x0D, '[': 0x1A, ']': 0x1B,
	';': 0x27, '\'': 0x28, '`': 0x29, '\\': 0x2B,
	',': 0x33, '.': 0x34, '/': 0x35, ' ': 0x39,
}

var usScanShift = map[rune]uint16{
	'~': 0x29, '!': 0x02, '@': 0x03, '#': 0x04, '$': 0x05, '%': 0x06,
	'^': 0x07, '&': 0x08, '*': 0x09, '(': 0x0A, ')': 0x0B,
	'_': 0x0C, '+': 0x0D, '{': 0x1A, '}': 0x1B, ':': 0x27, '"': 0x28,
	'|': 0x2B, '<': 0x33, '>': 0x34, '?': 0x35,
}

func canTypeASCII(s string) bool {
	for _, r := range s {
		if _, ok := usScanShift[r]; ok {
			continue
		}
		if r >= 'A' && r <= 'Z' {
			_, ok := usScan[r-'A'+'a']
			if !ok {
				return false
			}
			continue
		}
		if _, ok := usScan[r]; !ok {
			return false
		}
	}
	return true
}

func altNumpadVKs() []uint16 {
	return []uint16{VK_MENU, VK_NUMPAD2, VK_NUMPAD1}
}
